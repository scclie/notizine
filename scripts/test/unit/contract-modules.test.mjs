test('header escapes HTML-special characters in rendered titles', async () => {
  const gen = await loadGen('header');
  const fallback = await gen({ page: page('xx', '/xx/'), site: MODEL, params: { title: 'A <b>&</b> "B"' } });
  assert.equal(fallback, '<a href="/" class="site-title">A &lt;b&gt;&amp;&lt;/b&gt; &quot;B&quot;</a>');
  const titled = {
    ...MODEL,
    pages: [page('ru', '/ru/', 'H "ome" <1>'), page('ru', '/x/')],
  };
  const home = await gen({ page: titled.pages[1], site: titled, params: {} });
  assert.equal(home, '<a href="/ru/" class="site-title">H &quot;ome&quot; &lt;1&gt;</a>');
});
