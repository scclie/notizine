import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homeLink } from '../../lib/api.mjs';
import { v2Slots } from '../../lib/render.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const modulePath = (name, file) => join(REPO, 'modules', name, file);
const loadGen = async name => (await import(new URL(`../../../modules/${name}/generator.mjs`, import.meta.url).href)).default;

function page(locale, link, title = '') {
  return { locale, link, title, isSection: true };
}

const MODEL = {
  config: {
    site: {
      locales: [
        { code: 'en', output_prefix_override: '' },
        { code: 'ru', output_prefix_override: null },
      ],
      social: {},
      features: {},
    },
  },
  pages: [page('en', '/', 'notizine EN'), page('ru', '/ru/', 'notizine RU')],
};

const t = map => key => map[key] ?? key;
const RU = t({ generated_by: 'Сгенерировано', with: 'с помощью' });
const EN = t({ generated_by: 'Generated by', with: 'with' });

function captureWarn(fn) {
  const warns = [];
  const orig = console.warn;
  console.warn = msg => warns.push(String(msg));
  try {
    return { result: fn(), warns };
  } finally {
    console.warn = orig;
  }
}

