test('badges defaults to the legacy markup and honors params.items', async () => {
  const gen = await loadGen('badges');
  const def = await gen({ params: {} });
  assert.equal(def, readFileSync(modulePath('badges', 'template.html'), 'utf-8'));
  assert.ok(def.includes('https://zine-ssg.io/'));
  const custom = await gen({
    params: { id: 'badges', module: 'badges', items: [{ href: 'https://x.example/', src: 'data:image/gif;base64,R0=', alt: 'X <1>' }] },
  });
  assert.ok(custom.includes('href="https://x.example/"'));
  assert.ok(custom.includes('alt="X &lt;1&gt;"'));
  assert.ok(!custom.includes('zine-ssg.io'));
});

test('social renders configured github and mastodon links only', async () => {
  const gen = await loadGen('social');
  const both = await gen({ site: { config: { social: { github: 'octocat', mastodon: 'https://mastodon.social/@octo' } } } });
  assert.ok(both.includes('<a href="https://github.com/octocat" class="social-link" target="_blank" rel="noopener">GitHub</a>'));
  assert.ok(both.includes('<a href="https://mastodon.social/@octo" rel="me" class="social-link">Mastodon</a>'));
  const ghOnly = await gen({ site: { config: { social: { github: 'octocat', mastodon: '' } } } });
  assert.ok(ghOnly.includes('github.com/octocat'));
  assert.ok(!ghOnly.includes('mastodon.social'));
  const empty = await gen({ site: { config: { social: {} } } });
  assert.equal(empty, '');
});

test('rss_link follows features.rss and points at locale posts feed', async () => {
  const gen = await loadGen('rss_link');
  const model = {
    config: { features: { rss: true } },
    pages: [
      { locale: 'en', isSection: true, link: '/posts/' },
      { locale: 'ru', isSection: true, link: '/ru/posts/' },
    ],
  };
  const en = await gen({ page: { locale: 'en' }, site: model });
  assert.equal(en, '<a href="/posts/index.xml" class="rss-link">RSS</a>');
  const ru = await gen({ page: { locale: 'ru' }, site: model });
  assert.equal(ru, '<a href="/ru/posts/index.xml" class="rss-link">RSS</a>');
  assert.equal(await gen({ page: { locale: 'en' }, site: { config: { features: { rss: false } }, pages: model.pages } }), '');
  assert.equal(await gen({ page: { locale: 'de' }, site: model }), '');
});

test('v2Slots no longer drops migrated sitewide or per-page modules', () => {
  const { result, warns } = captureWarn(() =>
    v2Slots({ footer: [['_social', '_rss_link']], before_main: [['_breadcrumbs', '_prev_next']] })
  );
  assert.deepEqual(result.footer, [[{ module: '_social', id: '_social' }, { module: '_rss_link', id: '_rss_link' }]]);
  assert.deepEqual(result.before_main, [[
    { module: '_breadcrumbs', id: '_breadcrumbs' },
    { module: '_prev_next', id: '_prev_next' },
  ]]);
  assert.deepEqual(warns, []);
});

function leaf(locale, link, extra = {}) {
  return {
    locale,
    link,
    title: '',
    description: '',
    date: '',
    moddate: '',
    tags: [],
    isSection: false,
    parentLink: null,
    wordcount: 0,
    readtime: 1,
    filePath: '',
    ...extra,
  };
}

const FAKE_MODEL = {
  config: {
    site: {
      locales: [
        { code: 'en', output_prefix_override: '' },
        { code: 'ru', output_prefix_override: null },
      ],
    },
  },
  pages: [
    leaf('en', '/', { title: 'notizine EN', isSection: true }),
    leaf('en', '/posts/', { title: 'Posts', isSection: true, parentLink: '/' }),
    leaf('en', '/about/', { title: 'About', parentLink: '/' }),
    leaf('en', '/posts/a/', { title: 'Post A', date: '2026-02-01', parentLink: '/posts/', filePath: '/c/en/posts/a.smd' }),
    leaf('en', '/posts/b/', { title: 'Post B', date: '2026-03-01', parentLink: '/posts/', filePath: '/c/en/posts/b.smd' }),
    leaf('ru', '/ru/', { title: 'notizine RU', isSection: true }),
    leaf('ru', '/ru/posts/', { title: 'Записи', isSection: true, parentLink: '/ru/' }),
    leaf('ru', '/ru/posts/b/', { title: 'Пост Б', date: '2026-03-01', parentLink: '/ru/posts/', filePath: '/c/ru/posts/b.smd' }),
  ],
};

test('breadcrumbs renders home, parent section and escaped page title', async () => {
  const gen = await loadGen('breadcrumbs');
  const nested = await gen({
    page: FAKE_MODEL.pages[3],
    site: FAKE_MODEL,
    params: {},
    i18n: t({ home: 'Home' }),
  });
  assert.equal(
    nested,
    '<nav class="breadcrumbs"><a href="/">Home</a><span class="crumb-sep">/</span>' +
    '<a href="/posts/">Posts</a><span class="crumb-sep">/</span><span>Post A</span></nav>'
  );
  const topLevel = await gen({
    page: FAKE_MODEL.pages[2],
    site: FAKE_MODEL,
    params: {},
    i18n: t({ home: 'Home' }),
  });
  assert.equal(
    topLevel,
    '<nav class="breadcrumbs"><a href="/">Home</a><span class="crumb-sep">/</span><span>About</span></nav>'
  );
});

test('breadcrumbs skips sections and escapes special characters', async () => {
  const gen = await loadGen('breadcrumbs');
  assert.equal(await gen({ page: FAKE_MODEL.pages[1], site: FAKE_MODEL, params: {}, i18n: t({}) }), '');
  const spiky = await gen({
    page: leaf('en', '/posts/x/', { title: 'Q & <R> "S"', parentLink: '/posts/' }),
    site: FAKE_MODEL,
    params: {},
    i18n: t({ home: 'Home' }),
  });
  assert.ok(spiky.includes('<span>Q &amp; &lt;R&gt; &quot;S&quot;</span>'));
});

